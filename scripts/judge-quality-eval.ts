// Output
// ---------------------------------------------------------------------------


function printTable(
  perCriterion: ReferenceSummary,
  consolidated: ReferenceSummary,
  verdict: Record<string, Side | 'tie'>,
  reference: CallUsageReport,
): void {
  console.log(`\n[quality] distance from ${REFERENCE_MODEL} (1–5 scale; bias > 0 = more lenient)`);
  console.log(
    tableRow(TABLE_CELL_WIDTH, 'criterion', 'n', 'pc exact', 'pc mae', 'pc bias', 'cons exact', 'cons mae', 'cons bias')
    + padCell('closer', CLOSER_CELL_WIDTH),
  );
  const names = [...Object.keys(verdict), 'overall'];
  for (const name of names) {
    const a = name === 'overall' ? perCriterion.overall : perCriterion.byCriterion[name];
    const b = name === 'overall' ? consolidated.overall : consolidated.byCriterion[name];
    const closer = name === 'overall'
      ? ((a?.meanAbsDiff ?? Infinity) < (b?.meanAbsDiff ?? Infinity) ? 'perCriterion' : 'consolidated')
      : verdict[name]!;
    console.log(
      tableRow(
        TABLE_CELL_WIDTH,
        name,
        Math.max(a?.paired ?? 0, b?.paired ?? 0),
        formatRate(a?.exactMatchRate ?? null),
        formatDiff(a?.meanAbsDiff ?? null),
        formatDiff(a?.meanSignedDiff ?? null),
        formatRate(b?.exactMatchRate ?? null),
        formatDiff(b?.meanAbsDiff ?? null),
        formatDiff(b?.meanSignedDiff ?? null),
      ) + padCell(closer, CLOSER_CELL_WIDTH),
    );
  }
  console.log(
    `\n[quality] reference: ${reference.calls} calls, ${reference.inputTokens} input / ${reference.outputTokens} output tokens, `
    + `${formatUsd(reference.usd)}`,
  );
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main(): Promise<void> {
  const args = parseArgs(process.argv.slice(2));
  const credential = admitOneShot(runGuard, args);
  if (!credential) return;

  const pricing = judgePricing(REFERENCE_MODEL);

  const agreementPath = resolveAgreementPath(DOCS_DIR, args.agreementPath);
  if (!agreementPath) return refuse('no judge-agreement results file to evaluate; run judge-agreement.ts first');
  const agreementTurns = readAgreementTurns(agreementPath);
  console.log(`[quality] ${agreementTurns.length} scored turns from ${agreementPath}`);

  const turns = await loadOrFreezeTurns(agreementTurns);
  const byKey = new Map(turns.map(t => [turnKey(t), t]));
  const matched = agreementTurns.filter(t => byKey.has(turnKey(t)));
  const unmatched = agreementTurns.length - matched.length;
  console.log(`[quality] ${matched.length} turns matched, ${unmatched} no longer locatable`);
  if (matched.length === 0) return refuse('none of the agreement run\'s turns could be located');

  const estimate = estimateReferenceSpend(matched.map(t => byKey.get(turnKey(t))!), pricing);
  console.log(
    `[quality] estimate: ~${estimate.calls} reference calls, ~${estimate.inputTokens.toLocaleString()} input / `
    + `~${estimate.outputTokens.toLocaleString()} output tokens, ~${formatUsd(estimate.usd)} `
    + `(plus one steps call per criterion)`,
  );
  const overCap = spendCapReason(estimate.usd, MAX_ESTIMATED_SPEND_USD);
  if (overCap) return refuse(overCap);

  const startedAt = begin(DOCS_DIR, { agreementPath, turns: matched.length });
  if (!startedAt) return;

  const totals: CallUsageTotals = createCallUsageTotals();
  const provider = await createReferenceProvider(credential.apiKey, usage => addCallUsage(totals, usage));
  const canSpend = (): boolean => tokenUsageCostUsd(totals, pricing) < MAX_MEASURED_SPEND_USD;
  const stepsCache: EvaluationStepsCache = new Map();
  const turnErrors: TurnErrors[] = [];

  const progress = turnProgress('[quality]', matched.length);
  const scored = await processBatch(matched, REFERENCE_CONCURRENCY, NO_BATCH_DELAY_MS, async (turn): Promise<QualityTurn> => {
    const errors: string[] = [];
    const reference = await scoreTurnWithReference(provider, byKey.get(turnKey(turn))!, stepsCache, canSpend, errors);
    if (errors.length > 0) turnErrors.push({ sessionId: turn.sessionId, timestamp: turn.timestamp, errors });
    progress(` (${formatUsd(tokenUsageCostUsd(totals, pricing))} so far)`);
    return { ...turn, reference };
  });

  const perCriterion = compareToReference(scored, 'perCriterion');
  const consolidated = compareToReference(scored, 'consolidated');
  const verdict = closerConfiguration(perCriterion, consolidated);
  const referenceUsage: CallUsageReport = { ...totals, usd: tokenUsageCostUsd(totals, pricing) };

  const results = {
    generatedAt: new Date().toISOString(),
    startedAt: startedAt.toISOString(),
    agreementSource: agreementPath,
    reference: {
      model: REFERENCE_MODEL,
      effort: REFERENCE_EFFORT,
      method: 'G-Eval, one call per criterion, reference-generated steps; hallucination = 1 - faithfulness',
      pricingUsdPerMillion: { input: pricing.input, output: pricing.output },
      usage: referenceUsage,
    },
    turnsRequested: agreementTurns.length,
    turnsEvaluated: scored.length,
    turnsUnlocatable: unmatched,
    estimate,
    distance: { perCriterion, consolidated },
    closer: verdict,
    failures: turnErrors,
    turns: scored,
  };

  const outPath = writeResults(runGuard, startedAt, results);
  printTable(perCriterion, consolidated, verdict, referenceUsage);
  console.log(`\n[quality] results written: ${outPath}`);
}

runIfMain(import.meta.url, main, '[quality]', { fatalExitCode: EXIT_REFUSED });
