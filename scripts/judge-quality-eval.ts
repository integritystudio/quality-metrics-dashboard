#!/usr/bin/env tsx
/**
 * Judge quality eval (JCP4): which Haiku configuration is closer to a reference?
 *
 * judge-agreement.ts measured that the per-criterion and consolidated judges
 * disagree; it cannot say which one is right. This script scores the SAME
 * turns with a stronger reference judge and measures each configuration's
 * distance from it.
 *
 * - Inputs: the Haiku scores already paid for in docs/judge-agreement-*.json.
 *   Nothing is re-scored with Haiku.
 * - Turns: re-located by (sessionId, timestamp) through the pipeline's own
 *   transcript discovery and frozen to local/ (gitignored — raw transcript
 *   content never enters the repo). A re-run reads the frozen file.
 * - Reference: REFERENCE_MODEL, one call PER CRITERION (no halo effect across
 *   criteria), with its own evaluation steps generated by the same model — so
 *   it inherits neither Haiku's steps nor the consolidated single-call format.
 *   faithfulness is G-Eval on FAITHFULNESS_CRITERIA (the per-criterion path
 *   uses QAG) and hallucination is 1 - faithfulness, as on both Haiku paths.
 *
 * Safety rules, all mandatory:
 * - `--yes` is required.
 * - A marker (docs/.judge-quality.started) is written before the first API
 *   call; the script refuses while the marker or any results file exists.
 * - Refuses up front when the estimate exceeds MAX_ESTIMATED_SPEND_USD, and
 *   stops issuing calls once MEASURED spend reaches MAX_MEASURED_SPEND_USD.
 *
 * Usage:
 *   doppler run -p integrity-studio -c prd -- npx tsx scripts/judge-quality-eval.ts --yes
 */

