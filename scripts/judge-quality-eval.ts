// ---------------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------------

export const REFERENCE_MODEL = 'claude-opus-5';
/** Intelligence-sensitive grading: do not trade reference quality for cost. */
export const REFERENCE_EFFORT = 'high';
/** Thinking counts against max_tokens; non-streaming stays under the SDK timeout at this size. */
const REFERENCE_MAX_TOKENS = 16_000;
export const REFERENCE_CONCURRENCY = 4;
/**
 * Spend approved for this run on 2026-09-22 was $10. The measured cap is
 * checked before every call, so the overrun is bounded by the calls already
 * in flight (REFERENCE_CONCURRENCY) and the total stays under the approval.
 */
export const MAX_ESTIMATED_SPEND_USD = 9.5;
export const MAX_MEASURED_SPEND_USD = 9.5;
/** Estimate only: adaptive thinking plus the reasoning field, per reference call. */
export const OUTPUT_TOKENS_PER_CALL_ESTIMATE = 1_500;
/** Estimate only: criterion text, steps and anchoring added to the turn content. */
export const PROMPT_OVERHEAD_TOKENS_ESTIMATE = 600;
export const AGREEMENT_FLAG = '--agreement';
export const MARKER_FILENAME = '.judge-quality.started';
export const RESULTS_PREFIX = 'judge-quality-';
export const FROZEN_TURNS_PATH = join(dirname(fileURLToPath(import.meta.url)), '..', 'local', 'judge-quality-turns.json');

const JSON_SCHEMA_OUTPUT_FORMAT = 'json_schema';
const MAX_TOKENS_STOP_REASON = 'max_tokens';
const REFUSAL_STOP_REASON = 'refusal';
const TABLE_CELL_WIDTH = 11;
/** The verdict column is wider than the rest. */
const CLOSER_CELL_WIDTH = TABLE_CELL_WIDTH + 2;

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export type ParsedArgs = OneShotArgs & { agreementPath?: string };

/** One turn of a judge-agreement results file. */
export interface AgreementTurn {
  sessionId: string;
  timestamp: string;
  hasTools: boolean;
  expected: string[];
  perCriterion: Record<string, number>;
  consolidated: Record<string, number>;
}

export interface QualityTurn extends AgreementTurn {
  reference: Record<string, number>;
}

export type Side = 'perCriterion' | 'consolidated';

/** A configuration's distance from the reference, per criterion, on the 1–5 scale. */
export interface ReferenceDistance {
  paired: number;
  exactMatchRate: number | null;
  meanAbsDiff: number | null;
  /** Mean of (configuration - reference): positive = more lenient than the reference. */
  meanSignedDiff: number | null;
  /** Scored by the configuration, not by the reference. */
  configOnly: number;
  /** Scored by the reference, missing from the configuration. */
  referenceOnly: number;
}

export interface ReferenceSummary {
  byCriterion: Record<string, ReferenceDistance>;
  overall: ReferenceDistance;
}

// ---------------------------------------------------------------------------
// Arguments and files
// ---------------------------------------------------------------------------

export function parseArgs(argv: readonly string[]): ParsedArgs {
  return parseOneShotArgs<{ agreementPath?: string }>(argv, { values: [AGREEMENT_FLAG] }, {}, cli => {
    const agreementPath = cli.value(AGREEMENT_FLAG);
    return agreementPath === undefined ? {} : { agreementPath };
  });
}

const runGuard = createRunGuard({ markerFilename: MARKER_FILENAME, resultsPrefix: RESULTS_PREFIX, logPrefix: '[quality]', noun: 'eval' });
export const { listResultsFiles, resultsFilePath, refusalReason } = runGuard;
const { refuse, begin } = runGuard;

/** The newest judge-agreement results file, unless one was named. */
export function resolveAgreementPath(docsDir: string, explicit?: string): string | undefined {
  if (explicit) return explicit;
  const files = listAgreementFiles(docsDir);
  const latest = files[files.length - 1];
  return latest ? join(docsDir, latest) : undefined;
}

export function readAgreementTurns(path: string): AgreementTurn[] {
  const parsed = JSON.parse(readFileSync(path, 'utf8')) as { turns?: AgreementTurn[] };
  if (!Array.isArray(parsed.turns)) throw new Error(`${path} has no turns array — not a judge-agreement results file`);
  return parsed.turns;
}

// ---------------------------------------------------------------------------
// Freezing the turns
// ---------------------------------------------------------------------------

export function turnKey(turn: { sessionId: string; timestamp: string }): string {
  return `${turn.sessionId}|${turn.timestamp}`;
}

/** Re-locate the scored turns through the pipeline's own discovery. Unmatched turns are simply absent. */
async function locateTurns(wanted: readonly AgreementTurn[]): Promise<Turn[]> {
  const keys = new Set(wanted.map(turnKey));
  const sessions = new Set(wanted.map(t => t.sessionId));
  const found: Turn[] = [];
  for (const info of await _discoverTranscripts()) {
    if (!sessions.has(info.sessionId)) continue;
    for (const turn of await extractTurns(info)) {
      if (keys.has(turnKey(turn))) found.push(turn);
    }
  }
  return found;
}

async function loadOrFreezeTurns(wanted: readonly AgreementTurn[]): Promise<Turn[]> {
  if (existsSync(FROZEN_TURNS_PATH)) {
    console.log(`[quality] frozen turns read from ${FROZEN_TURNS_PATH}`);
    return JSON.parse(readFileSync(FROZEN_TURNS_PATH, 'utf8')) as Turn[];
  }
  console.log('[quality] locating the agreement run\'s turns through the pipeline…');
  const turns = await locateTurns(wanted);
  mkdirSync(dirname(FROZEN_TURNS_PATH), { recursive: true });
  writeFileSync(FROZEN_TURNS_PATH, JSON.stringify(turns, null, JSON_INDENT) + '\n');
  console.log(`[quality] ${turns.length} turns frozen to ${FROZEN_TURNS_PATH}`);
  return turns;
}

// ---------------------------------------------------------------------------
// Estimate
// ---------------------------------------------------------------------------

/** Tokens one reference call sends for this criterion — only the parts the criterion reads. */
export function estimateCallInputTokens(turn: Turn, config: GEvalConfig): number {
  const params = new Set(config.evaluationParams);
  const chars = (params.has('input') ? turn.userText.length : 0)
    + (params.has('output') ? turn.assistantText.length : 0)
    + (params.has('context') ? totalChars(fitContextForJudge(turn.toolResults)) : 0);
  return charsToTokens(chars) + PROMPT_OVERHEAD_TOKENS_ESTIMATE;
}

export function estimateReferenceSpend(
  turns: readonly Turn[],
  pricing: ModelPricingEntry,
): { calls: number; inputTokens: number; outputTokens: number; usd: number } {
  let calls = 0;
  let inputTokens = 0;
  for (const turn of turns) {
    for (const config of selectCriteria(turn, new Set()).criteria) {
      calls++;
      inputTokens += estimateCallInputTokens(turn, config);
    }
  }
  const outputTokens = calls * OUTPUT_TOKENS_PER_CALL_ESTIMATE;
  const usd = listCostUsd(inputTokens, outputTokens, pricing);
  return { calls, inputTokens, outputTokens, usd };
}

// ---------------------------------------------------------------------------
// Distance from the reference
// ---------------------------------------------------------------------------

/**
 * Each configuration against the reference. Exact match and MAE come from
 * computeAgreement (configuration in the first slot, reference in the second);
 * the signed mean is added here because agreement has no direction.
 */
export function compareToReference<K extends string>(
  turns: readonly (Record<K, Record<string, number>> & { reference: Record<string, number> })[],
  side: K,
): ReferenceSummary {
  const agreement = computeAgreement(turns.map(t => ({ perCriterion: t[side], consolidated: t.reference })));

  const signedSums = new Map<string, number>();
  let overallSigned = 0;
  for (const turn of turns) {
    for (const [name, value] of Object.entries(turn[side])) {
      const reference = turn.reference[name];
      if (reference === undefined) continue;
      const diff = toFivePointScale(value) - toFivePointScale(reference);
      signedSums.set(name, (signedSums.get(name) ?? 0) + diff);
      overallSigned += diff;
    }
  }

  const toDistance = (entry: CriterionAgreement, signedSum: number): ReferenceDistance => ({
    paired: entry.paired,
    exactMatchRate: entry.exactMatchRate,
    meanAbsDiff: entry.meanAbsDiff,
    meanSignedDiff: entry.paired > 0 ? signedSum / entry.paired : null,
    configOnly: entry.perCriterionOnly,
    referenceOnly: entry.consolidatedOnly,
  });

  const byCriterion: Record<string, ReferenceDistance> = {};
  for (const [name, entry] of Object.entries(agreement.byCriterion)) {
    byCriterion[name] = toDistance(entry, signedSums.get(name) ?? 0);
  }
  return { byCriterion, overall: toDistance(agreement.overall, overallSigned) };
}

/** Per criterion, the configuration with the lower MAE against the reference; 'tie' when equal or unpaired. */
export function closerConfiguration(
  perCriterion: ReferenceSummary,
  consolidated: ReferenceSummary,
): Record<string, Side | 'tie'> {
  const names = new Set([...Object.keys(perCriterion.byCriterion), ...Object.keys(consolidated.byCriterion)]);
  const verdict: Record<string, Side | 'tie'> = {};
  for (const name of [...names].sort()) {
    const a = perCriterion.byCriterion[name]?.meanAbsDiff ?? null;
    const b = consolidated.byCriterion[name]?.meanAbsDiff ?? null;
    if (a === null || b === null || a === b) verdict[name] = 'tie';
    else verdict[name] = a < b ? 'perCriterion' : 'consolidated';
  }
  return verdict;
}

