/**
 * REFERENCE_MODEL behind the ConsolidatedProvider interface. Sampling
 * parameters are rejected on this model, so options.temperature is dropped;
 * thinking is adaptive and effort is pinned so the reference is reproducible
 * in configuration, if not in output.
 */
export async function createReferenceProvider(
  apiKey: string,
  onUsage: (usage: JudgeTokenUsage) => void,
): Promise<ConsolidatedProvider> {
  const client = await createJudgeAnthropicClient({ apiKey });
  return {
    async generate(prompt: string, options: ConsolidatedGenerateOptions = {}): Promise<ConsolidatedResponse> {
      const response = await client.messages.create({
        model: REFERENCE_MODEL,
        max_tokens: REFERENCE_MAX_TOKENS,
        thinking: { type: 'adaptive' },
        output_config: {
          effort: REFERENCE_EFFORT,
          ...(options.schema && { format: { type: JSON_SCHEMA_OUTPUT_FORMAT, schema: options.schema } }),
        },
        messages: [{ role: 'user', content: prompt }],
      });
      const usage = toJudgeTokenUsage(response.usage);
      onUsage(usage);
      if (response.stop_reason === REFUSAL_STOP_REASON) {
        throw new Error(`Reference declined (${response.stop_details?.category ?? 'no category'})`);
      }
      if (response.stop_reason === MAX_TOKENS_STOP_REASON) {
        throw new Error(`Reference truncated at ${MAX_TOKENS_STOP_REASON}`);
      }
      const text = responseText(response.content);
      return { text, usage };
    },
  };
}

/**
 * One call per criterion. Returns normalized (0–1) scores keyed by record
 * name, with hallucination derived as 1 - faithfulness. A failed criterion is
 * absent and its error lands in `errors`.
 */
async function scoreTurnWithReference(
  provider: ConsolidatedProvider,
  turn: Turn,
  stepsCache: EvaluationStepsCache,
  canSpend: () => boolean,
  errors: string[],
): Promise<Record<string, number>> {
  const selection = selectCriteria(turn, new Set());
  const scores: Record<string, number> = {};

  for (const config of selection.criteria) {
    if (!canSpend()) {
      errors.push(`${config.name}: skipped, measured spend reached $${MAX_MEASURED_SPEND_USD}`);
      continue;
    }
    try {
      const normalized = await scoreCriterion(provider, turn, config, stepsCache);
      scores[config.name] = normalized;
      if (config.name === FAITHFULNESS_EVAL_NAME) scores[HALLUCINATION_EVAL_NAME] = 1 - normalized;
    } catch (err) {
      errors.push(`${config.name}: ${describeUnknown(err)}`);
    }
  }

  // Keep only the records the Haiku paths were expected to produce for this turn.
  return Object.fromEntries(Object.entries(scores).filter(([name]) => selection.recordNames.includes(name)));
}

