export const REFERENCE_MODEL = 'claude-opus-5';
/** Intelligence-sensitive grading: do not trade reference quality for cost. */
export const REFERENCE_EFFORT = 'high';
/** Thinking counts against max_tokens; non-streaming stays under the SDK timeout at this size. */
export const REFERENCE_MAX_TOKENS = 16_000;
export const REFERENCE_CONCURRENCY = 4;
/**
 * Spend approved for this run on 2026-09-22 was $10. The measured cap is
 * checked before every call, so the overrun is bounded by the calls already
 * in flight (REFERENCE_CONCURRENCY) and the total stays under the approval.
 */
export const MAX_ESTIMATED_SPEND_USD = 9.5;
export const MAX_MEASURED_SPEND_USD = 9.5;
/** Estimate only: adaptive thinking plus the reasoning field, per reference call. */
export const OUTPUT_TOKENS_PER_CALL_ESTIMATE = 1_500;
/** Estimate only: criterion text, steps and anchoring added to the turn content. */
export const PROMPT_OVERHEAD_TOKENS_ESTIMATE = 600;
export const YES_FLAG = '--yes';
export const AGREEMENT_FLAG = '--agreement';
export const MARKER_FILENAME = '.judge-quality.started';
export const RESULTS_PREFIX = 'judge-quality-';
export const FROZEN_TURNS_PATH = join(dirname(fileURLToPath(import.meta.url)), '..', 'local', 'judge-quality-turns.json');

const KNOWN_FLAGS: ReadonlySet<string> = new Set([YES_FLAG, AGREEMENT_FLAG]);
const JSON_SCHEMA_OUTPUT_FORMAT = 'json_schema';
const MAX_TOKENS_STOP_REASON = 'max_tokens';
const REFUSAL_STOP_REASON = 'refusal';
const ISO_DATE_LEN = 10;
const JSON_INDENT = 2;
const EXIT_REFUSED = 1;
const NO_BATCH_DELAY_MS = 0;
const PERCENT = 100;
const RATE_DECIMALS = 1;
const DIFF_DECIMALS = 3;
const USD_DECIMALS = 4;
const TABLE_NAME_WIDTH = 18;
const TABLE_CELL_WIDTH = 11;

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface ParsedArgs {
  yes: boolean;
  agreementPath?: string;
  /** Set when the invocation must be refused; the message says why. */
  error?: string;
}

/** One turn of a judge-agreement results file. */
export interface AgreementTurn {
  sessionId: string;
  timestamp: string;
  hasTools: boolean;
  expected: string[];
  perCriterion: Record<string, number>;
  consolidated: Record<string, number>;
}

export interface QualityTurn extends AgreementTurn {
  reference: Record<string, number>;
}

export type Side = 'perCriterion' | 'consolidated';

/** A configuration's distance from the reference, per criterion, on the 1–5 scale. */
export interface ReferenceDistance {
  paired: number;
  exactMatchRate: number | null;
  meanAbsDiff: number | null;
  /** Mean of (configuration - reference): positive = more lenient than the reference. */
  meanSignedDiff: number | null;
  /** Scored by the configuration, not by the reference. */
  configOnly: number;
  /** Scored by the reference, missing from the configuration. */
  referenceOnly: number;
}

export interface ReferenceSummary {
  byCriterion: Record<string, ReferenceDistance>;
  overall: ReferenceDistance;
}

// ---------------------------------------------------------------------------
// Arguments and files
// ---------------------------------------------------------------------------

export function parseArgs(argv: readonly string[]): ParsedArgs {
  const parsed: ParsedArgs = { yes: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]!;
    if (arg === YES_FLAG) {
      parsed.yes = true;
      continue;
    }
    if (arg === AGREEMENT_FLAG) {
      const value = argv[i + 1];
      if (!value || value.startsWith('--')) return { ...parsed, error: `${AGREEMENT_FLAG} needs a path` };
      parsed.agreementPath = value;
      i++;
      continue;
    }
    if (!KNOWN_FLAGS.has(arg)) return { ...parsed, error: `Unknown argument: ${arg} (there is no --force; remove the marker and results file by hand if you mean it)` };
  }
  if (!parsed.yes) return { ...parsed, error: `${YES_FLAG} is required: this run spends real API money` };
  return parsed;
}

export function listResultsFiles(docsDir: string): string[] {
  if (!existsSync(docsDir)) return [];
  return readdirSync(docsDir)
    .filter(f => f.startsWith(RESULTS_PREFIX) && f.endsWith(RESULTS_SUFFIX))
    .sort();
}

export function resultsFilePath(docsDir: string, date: Date): string {
  return join(docsDir, `${RESULTS_PREFIX}${date.toISOString().slice(0, ISO_DATE_LEN)}${RESULTS_SUFFIX}`);
}

/** Why the run must not start, or undefined when it may. */
export function refusalReason(docsDir: string): string | undefined {
  const marker = join(docsDir, MARKER_FILENAME);
  if (existsSync(marker)) return `marker exists: ${marker} — a run already started; this eval runs once`;
  const results = listResultsFiles(docsDir);
  if (results.length > 0) return `results already exist: ${results.join(', ')} — this eval runs once`;
  return undefined;
}

/** The newest judge-agreement results file, unless one was named. */
export function resolveAgreementPath(docsDir: string, explicit?: string): string | undefined {
  if (explicit) return explicit;
  const files = listAgreementFiles(docsDir);
  const latest = files[files.length - 1];
  return latest ? join(docsDir, latest) : undefined;
}

/** O_CREAT | O_EXCL: two concurrent starts cannot both win. */
function writeMarker(docsDir: string, payload: object): void {
  mkdirSync(docsDir, { recursive: true });
  const fd = openSync(join(docsDir, MARKER_FILENAME), constants.O_CREAT | constants.O_EXCL | constants.O_WRONLY);
  writeFileSync(fd, JSON.stringify(payload, null, JSON_INDENT) + '\n');
  closeSync(fd);
}

export function readAgreementTurns(path: string): AgreementTurn[] {
  const parsed = JSON.parse(readFileSync(path, 'utf8')) as { turns?: AgreementTurn[] };
  if (!Array.isArray(parsed.turns)) throw new Error(`${path} has no turns array — not a judge-agreement results file`);
  return parsed.turns;
}

// ---------------------------------------------------------------------------
// Freezing the turns
// ---------------------------------------------------------------------------

export function turnKey(turn: { sessionId: string; timestamp: string }): string {
  return `${turn.sessionId}|${turn.timestamp}`;
}

/** Re-locate the scored turns through the pipeline's own discovery. Unmatched turns are simply absent. */
async function locateTurns(wanted: readonly AgreementTurn[]): Promise<Turn[]> {
  const keys = new Set(wanted.map(turnKey));
  const sessions = new Set(wanted.map(t => t.sessionId));
  const found: Turn[] = [];
  for (const info of await _discoverTranscripts()) {
    if (!sessions.has(info.sessionId)) continue;
    for (const turn of await extractTurns(info)) {
      if (keys.has(turnKey(turn))) found.push(turn);
    }
  }
  return found;
}

async function loadOrFreezeTurns(wanted: readonly AgreementTurn[]): Promise<Turn[]> {
  if (existsSync(FROZEN_TURNS_PATH)) {
    console.log(`[quality] frozen turns read from ${FROZEN_TURNS_PATH}`);
    return JSON.parse(readFileSync(FROZEN_TURNS_PATH, 'utf8')) as Turn[];
  }
  console.log('[quality] locating the agreement run\'s turns through the pipeline…');
  const turns = await locateTurns(wanted);
  mkdirSync(dirname(FROZEN_TURNS_PATH), { recursive: true });
  writeFileSync(FROZEN_TURNS_PATH, JSON.stringify(turns, null, JSON_INDENT) + '\n');
  console.log(`[quality] ${turns.length} turns frozen to ${FROZEN_TURNS_PATH}`);
  return turns;
}

// ---------------------------------------------------------------------------
// Estimate
// ---------------------------------------------------------------------------

/** Tokens one reference call sends for this criterion — only the parts the criterion reads. */
export function estimateCallInputTokens(turn: Turn, config: GEvalConfig): number {
  const params = new Set(config.evaluationParams);
  const contextChars = params.has('context')
    ? fitContextForJudge(turn.toolResults).reduce((sum, item) => sum + item.length, 0)
    : 0;
  const chars = (params.has('input') ? turn.userText.length : 0)
    + (params.has('output') ? turn.assistantText.length : 0)
    + contextChars;
  return Math.ceil(chars * TOKENS_PER_CHAR) + PROMPT_OVERHEAD_TOKENS_ESTIMATE;
}

export function estimateReferenceSpend(
  turns: readonly Turn[],
  pricing: ModelPricingEntry,
): { calls: number; inputTokens: number; outputTokens: number; usd: number } {
  let calls = 0;
  let inputTokens = 0;
  for (const turn of turns) {
    for (const config of selectCriteria(turn, new Set()).criteria) {
      calls++;
      inputTokens += estimateCallInputTokens(turn, config);
    }
  }
  const outputTokens = calls * OUTPUT_TOKENS_PER_CALL_ESTIMATE;
  const usd = usageToUsd(
    { inputTokens, outputTokens, cacheCreationInputTokens: 0, cacheReadInputTokens: 0 },
    pricing,
  );
  return { calls, inputTokens, outputTokens, usd };
}

// ---------------------------------------------------------------------------
// Distance from the reference
// ---------------------------------------------------------------------------

/**
 * Each configuration against the reference. Exact match and MAE come from
 * computeAgreement (configuration in the first slot, reference in the second);
 * the signed mean is added here because agreement has no direction.
 */
export function compareToReference<K extends string>(
  turns: readonly (Record<K, Record<string, number>> & { reference: Record<string, number> })[],
  side: K,
): ReferenceSummary {
  const agreement = computeAgreement(turns.map(t => ({ perCriterion: t[side], consolidated: t.reference })));

  const signedSums = new Map<string, number>();
  let overallSigned = 0;
  for (const turn of turns) {
    for (const [name, value] of Object.entries(turn[side])) {
      const reference = turn.reference[name];
      if (reference === undefined) continue;
      const diff = toFivePointScale(value) - toFivePointScale(reference);
      signedSums.set(name, (signedSums.get(name) ?? 0) + diff);
      overallSigned += diff;
    }
  }

  const toDistance = (entry: CriterionAgreement, signedSum: number): ReferenceDistance => ({
    paired: entry.paired,
    exactMatchRate: entry.exactMatchRate,
    meanAbsDiff: entry.meanAbsDiff,
    meanSignedDiff: entry.paired > 0 ? signedSum / entry.paired : null,
    configOnly: entry.perCriterionOnly,
    referenceOnly: entry.consolidatedOnly,
  });

  const byCriterion: Record<string, ReferenceDistance> = {};
  for (const [name, entry] of Object.entries(agreement.byCriterion)) {
    byCriterion[name] = toDistance(entry, signedSums.get(name) ?? 0);
  }
  return { byCriterion, overall: toDistance(agreement.overall, overallSigned) };
}

/** Per criterion, the configuration with the lower MAE against the reference; 'tie' when equal or unpaired. */
export function closerConfiguration(
  perCriterion: ReferenceSummary,
  consolidated: ReferenceSummary,
): Record<string, Side | 'tie'> {
  const names = new Set([...Object.keys(perCriterion.byCriterion), ...Object.keys(consolidated.byCriterion)]);
  const verdict: Record<string, Side | 'tie'> = {};
  for (const name of [...names].sort()) {
    const a = perCriterion.byCriterion[name]?.meanAbsDiff ?? null;
    const b = consolidated.byCriterion[name]?.meanAbsDiff ?? null;
    if (a === null || b === null || a === b) verdict[name] = 'tie';
    else verdict[name] = a < b ? 'perCriterion' : 'consolidated';
  }
  return verdict;
}

// ---------------------------------------------------------------------------
// Reference provider
// ---------------------------------------------------------------------------

/**
 * REFERENCE_MODEL behind the ConsolidatedProvider interface. Sampling
 * parameters are rejected on this model, so options.temperature is dropped;
 * thinking is adaptive and effort is pinned so the reference is reproducible
 * in configuration, if not in output.
 */
export async function createReferenceProvider(
  apiKey: string,
  onUsage: (usage: JudgeTokenUsage) => void,
): Promise<ConsolidatedProvider> {
  const client = await createJudgeAnthropicClient({ apiKey });
  return {
    async generate(prompt: string, options: ConsolidatedGenerateOptions = {}): Promise<ConsolidatedResponse> {
      const response = await client.messages.create({
        model: REFERENCE_MODEL,
        max_tokens: REFERENCE_MAX_TOKENS,
        thinking: { type: 'adaptive' },
        output_config: {
          effort: REFERENCE_EFFORT,
          ...(options.schema && { format: { type: JSON_SCHEMA_OUTPUT_FORMAT, schema: options.schema } }),
        },
        messages: [{ role: 'user', content: prompt }],
      });
      const usage = toJudgeTokenUsage(response.usage);
      onUsage(usage);
      if (response.stop_reason === REFUSAL_STOP_REASON) {
        throw new Error(`Reference declined (${response.stop_details?.category ?? 'no category'})`);
      }
      if (response.stop_reason === MAX_TOKENS_STOP_REASON) {
        throw new Error(`Reference truncated at ${MAX_TOKENS_STOP_REASON}`);
      }
      const text = response.content.flatMap(block => (block.type === 'text' ? [block.text] : [])).join('');
      return { text, usage };
    },
  };
}

/**
 * One call per criterion. Returns normalized (0–1) scores keyed by record
 * name, with hallucination derived as 1 - faithfulness. A failed criterion is
 * absent and its error lands in `errors`.
 */
async function scoreTurnWithReference(
  provider: ConsolidatedProvider,
  turn: Turn,
  stepsCache: EvaluationStepsCache,
  canSpend: () => boolean,
  errors: string[],
): Promise<Record<string, number>> {
  const selection = selectCriteria(turn, new Set());
  const toolContext = fitContextForJudge(turn.toolResults);
  const scores: Record<string, number> = {};

  for (const config of selection.criteria) {
    if (!canSpend()) {
      errors.push(`${config.name}: skipped, measured spend reached $${MAX_MEASURED_SPEND_USD}`);
      continue;
    }
    try {
      const steps = await cachedEvaluationSteps(provider, config, stepsCache);
      const prompt = buildConsolidatedPrompt(turn, toolContext, [{ config, steps }]);
      const response = await provider.generate(prompt, { schema: buildConsolidatedSchema([config.name]) });
      const verdict = parseConsolidatedResponse(response.text, [config.name]);
      const parsed = verdict.verdicts.get(config.name);
      if (!parsed) throw verdict.failures.get(config.name) ?? new Error(`no verdict for ${config.name}`);
      const normalized = toNormalizedScore(parsed.score);
      scores[config.name] = normalized;
      if (config.name === FAITHFULNESS_EVAL_NAME) scores[HALLUCINATION_EVAL_NAME] = 1 - normalized;
    } catch (err) {
      errors.push(`${config.name}: ${err instanceof Error ? err.message : String(err)}`);
    }
  }

  // Keep only the records the Haiku paths were expected to produce for this turn.
  return Object.fromEntries(Object.entries(scores).filter(([name]) => selection.recordNames.includes(name)));
}

// ---------------------------------------------------------------------------
// Output
// ---------------------------------------------------------------------------

function cell(value: string | number, width = TABLE_CELL_WIDTH): string {
  return String(value).padStart(width);
}

function formatRate(rate: number | null): string {
  return rate === null ? '-' : `${(rate * PERCENT).toFixed(RATE_DECIMALS)}%`;
}

function formatDiff(diff: number | null): string {
  return diff === null ? '-' : diff.toFixed(DIFF_DECIMALS);
}

function printTable(
  perCriterion: ReferenceSummary,
  consolidated: ReferenceSummary,
  verdict: Record<string, Side | 'tie'>,
  reference: UsageReport,
): void {
  console.log(`\n[quality] distance from ${REFERENCE_MODEL} (1–5 scale; bias > 0 = more lenient)`);
  console.log(
    `${'criterion'.padEnd(TABLE_NAME_WIDTH)}${cell('n')}${cell('pc exact')}${cell('pc mae')}${cell('pc bias')}`
    + `${cell('cons exact')}${cell('cons mae')}${cell('cons bias')}${cell('closer', TABLE_CELL_WIDTH + 2)}`,
  );
  const names = [...Object.keys(verdict), 'overall'];
  for (const name of names) {
    const a = name === 'overall' ? perCriterion.overall : perCriterion.byCriterion[name];
    const b = name === 'overall' ? consolidated.overall : consolidated.byCriterion[name];
    const closer = name === 'overall'
      ? ((a?.meanAbsDiff ?? Infinity) < (b?.meanAbsDiff ?? Infinity) ? 'perCriterion' : 'consolidated')
      : verdict[name]!;
    console.log(
      `${name.padEnd(TABLE_NAME_WIDTH)}${cell(Math.max(a?.paired ?? 0, b?.paired ?? 0))}`
      + `${cell(formatRate(a?.exactMatchRate ?? null))}${cell(formatDiff(a?.meanAbsDiff ?? null))}${cell(formatDiff(a?.meanSignedDiff ?? null))}`
      + `${cell(formatRate(b?.exactMatchRate ?? null))}${cell(formatDiff(b?.meanAbsDiff ?? null))}${cell(formatDiff(b?.meanSignedDiff ?? null))}`
      + `${cell(closer, TABLE_CELL_WIDTH + 2)}`,
    );
  }
  console.log(
    `\n[quality] reference: ${reference.calls} calls, ${reference.inputTokens} input / ${reference.outputTokens} output tokens, `
    + `$${reference.usd.toFixed(USD_DECIMALS)}`,
  );
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function refuse(message: string): void {
  console.error(`[quality] refused: ${message}`);
  process.exitCode = EXIT_REFUSED;
}

async function main(): Promise<void> {
  const args = parseArgs(process.argv.slice(2));
  if (args.error) {
    refuse(args.error);
    return;
  }

  const credential = resolveApiKey(process.env);
  if (!credential) {
    refuse(`no API key: set ${PRIMARY_KEY_ENV} (or ${FALLBACK_KEY_ENV})`);
    return;
  }
  console.log(`[quality] API key from ${credential.source}`);

  const reason = refusalReason(DOCS_DIR);
  if (reason) {
    refuse(reason);
    return;
  }

  const pricing = MODEL_PRICING[REFERENCE_MODEL];
  if (!pricing) {
    refuse(`no pricing data for model ${REFERENCE_MODEL}`);
    return;
  }

  const agreementPath = resolveAgreementPath(DOCS_DIR, args.agreementPath);
  if (!agreementPath) {
    refuse('no judge-agreement results file to evaluate; run judge-agreement.ts first');
    return;
  }
  const agreementTurns = readAgreementTurns(agreementPath);
  console.log(`[quality] ${agreementTurns.length} scored turns from ${agreementPath}`);

  const turns = await loadOrFreezeTurns(agreementTurns);
  const byKey = new Map(turns.map(t => [turnKey(t), t]));
  const matched = agreementTurns.filter(t => byKey.has(turnKey(t)));
  const unmatched = agreementTurns.length - matched.length;
  console.log(`[quality] ${matched.length} turns matched, ${unmatched} no longer locatable`);
  if (matched.length === 0) {
    refuse('none of the agreement run\'s turns could be located');
    return;
  }

  const estimate = estimateReferenceSpend(matched.map(t => byKey.get(turnKey(t))!), pricing);
  console.log(
    `[quality] estimate: ~${estimate.calls} reference calls, ~${estimate.inputTokens.toLocaleString()} input / `
    + `~${estimate.outputTokens.toLocaleString()} output tokens, ~$${estimate.usd.toFixed(USD_DECIMALS)} `
    + `(plus one steps call per criterion)`,
  );
  if (estimate.usd > MAX_ESTIMATED_SPEND_USD) {
    refuse(`estimated spend $${estimate.usd.toFixed(USD_DECIMALS)} exceeds the $${MAX_ESTIMATED_SPEND_USD} cap`);
    return;
  }

  const lateReason = refusalReason(DOCS_DIR);
  if (lateReason) {
    refuse(lateReason);
    return;
  }
  const startedAt = new Date();
  writeMarker(DOCS_DIR, { startedAt: startedAt.toISOString(), pid: process.pid, agreementPath, turns: matched.length });
  console.log(`[quality] marker written: ${join(DOCS_DIR, MARKER_FILENAME)} — API calls start now`);

  const totals: UsageTotals = createUsageTotals();
  const provider = await createReferenceProvider(credential.key, usage => addUsage(totals, usage));
  const canSpend = (): boolean => usageToUsd(totals, pricing) < MAX_MEASURED_SPEND_USD;
  const stepsCache: EvaluationStepsCache = new Map();
  const turnErrors: { sessionId: string; timestamp: string; errors: string[] }[] = [];

  let completed = 0;
  const scored = await processBatch(matched, REFERENCE_CONCURRENCY, NO_BATCH_DELAY_MS, async (turn): Promise<QualityTurn> => {
    const errors: string[] = [];
    const reference = await scoreTurnWithReference(provider, byKey.get(turnKey(turn))!, stepsCache, canSpend, errors);
    if (errors.length > 0) turnErrors.push({ sessionId: turn.sessionId, timestamp: turn.timestamp, errors });
    completed++;
    console.log(`[quality] ${completed}/${matched.length} turns done ($${usageToUsd(totals, pricing).toFixed(USD_DECIMALS)} so far)`);
    return { ...turn, reference };
  });

  const perCriterion = compareToReference(scored, 'perCriterion');
  const consolidated = compareToReference(scored, 'consolidated');
  const verdict = closerConfiguration(perCriterion, consolidated);
  const referenceUsage: UsageReport = { ...totals, usd: usageToUsd(totals, pricing) };

  const results = {
    generatedAt: new Date().toISOString(),
    startedAt: startedAt.toISOString(),
    agreementSource: agreementPath,
    reference: {
      model: REFERENCE_MODEL,
      effort: REFERENCE_EFFORT,
      method: 'G-Eval, one call per criterion, reference-generated steps; hallucination = 1 - faithfulness',
      pricingUsdPerMillion: { input: pricing.input, output: pricing.output },
      usage: referenceUsage,
    },
    turnsRequested: agreementTurns.length,
    turnsEvaluated: scored.length,
    turnsUnlocatable: unmatched,
    estimate,
    distance: { perCriterion, consolidated },
    closer: verdict,
    failures: turnErrors,
    turns: scored,
  };

  const outPath = resultsFilePath(DOCS_DIR, startedAt);
  writeFileSync(outPath, JSON.stringify(results, null, JSON_INDENT) + '\n');
  printTable(perCriterion, consolidated, verdict, referenceUsage);
  console.log(`\n[quality] results written: ${outPath}`);
}

// Only run when executed directly (not imported as a module for testing)
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err: unknown) => {
    console.error('[quality] fatal:', err);
    process.exitCode = EXIT_REFUSED;
  });
}
